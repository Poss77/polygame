export function getSudokuPuzzleById(puzzleId) {
  if (!puzzleId || puzzleId < 1 || puzzleId > DAILY_SUDOKU_PUZZLES.length) return null;
  return DAILY_SUDOKU_PUZZLES[puzzleId - 1];
}

export function getSudokuPuzzleFallback(difficulty, seedIndex = 1) {
  const filtered = DAILY_SUDOKU_PUZZLES.filter(p => p.difficulty === (difficulty || 'medium'));
  if (filtered.length === 0) return DAILY_SUDOKU_PUZZLES[0];
  const idx = (Math.abs(seedIndex) % filtered.length);
  return filtered[idx];
}
